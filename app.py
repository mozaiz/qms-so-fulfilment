def _lan_addresses() -> list[str]:
    """Every non-loopback IPv4 address this box answers on — see netinfo.py.

    Shared with make_cert.py on purpose: the certificate must cover every address
    this screen shows, or a phone is handed an address its certificate does not
    match and the camera fails with no explanation.
    """
    return netinfo.local_ipv4()


