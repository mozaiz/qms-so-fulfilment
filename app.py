@app.get("/api/health")
def health():
    conn = get_db()
    try:
        n = conn.execute("SELECT COUNT(*) c FROM so_requests").fetchone()["c"]
        store = conn.execute("SELECT id, code FROM stores ORDER BY id LIMIT 1").fetchone()
        n_pos = pos_count_of(conn, store["id"]) if store else POS_COUNT
    except Exception:
        n = -1
        n_pos = POS_COUNT
    finally:
        conn.close()
    return {
        "ok": True, "time": iso(now()), "tz": str(TZ), "store": STORE_CODE,
        "requests_total": n,
        "stale_minutes": STALE_MINUTES,        # scanned -> nobody claimed it
        "sla_minutes": SLA_MINUTES,            # claimed -> not yet delivered
        "complete_minutes": COMPLETE_MINUTES,  # at counter -> POS has not closed it
        "pos_count": n_pos,
        "version": app.version,
    }


